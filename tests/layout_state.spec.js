const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'static/js/layout_editor.js'), 'utf8'), context);
const LayoutState = vm.runInContext('LayoutState', context);
const initial = { id: 'chart', x: 10, y: 30, w: 90, h: 60, page: 1 };
const state = new LayoutState([initial]);
state.change(model => { model.items[0].x = 11; model.items[0].y = 31; });
assert.strictEqual(state.dirty, true);
assert.strictEqual(state.items[0].x, 11, 'one-millimeter changes must survive a commit');
assert(state.undo());
assert.strictEqual(state.items[0].x, 10);
assert.strictEqual(state.dirty, false);
assert(state.redo());
assert.strictEqual(state.items[0].y, 31);
state.change(model => { model.items[0].x = 1000; model.items[0].y = -100; });
assert.strictEqual(state.items[0].x + state.items[0].w, 210);
assert.strictEqual(state.items[0].y, 30);
state.undo();
state.change(model => { model.items[0].w = 500; model.items[0].h = 1000; });
assert.strictEqual(state.items[0].x, 0);
assert.strictEqual(state.items[0].w, 210);
assert.strictEqual(state.items[0].h, 255);
assert.strictEqual(state.items[0].y + state.items[0].h, 285);
assert.strictEqual(state.future.length, 0, 'a new edit must replace the undone branch');
state.change(model => { model.pages = 2; model.items[0].page = 2; });
assert.strictEqual(state.pages, 2);
state.undo();
assert.strictEqual(state.pages, 1);
state.redo();
assert.strictEqual(state.items[0].page, 2);
state.saved = state.snapshot();
assert.strictEqual(state.dirty, false);
state.reset([initial]);
assert.strictEqual(state.past.length, 0);
assert.strictEqual(state.future.length, 0);
assert.strictEqual(initial.x, 10, 'draft changes must not mutate server data');
console.log('ok');
